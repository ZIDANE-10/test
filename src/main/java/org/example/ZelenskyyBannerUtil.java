    private static final byte[] PIXELS = Base64.getMimeDecoder().decode(PIXELS_BASE64);
    private static final String BANNER = createBanner();

    private ZelenskyyBannerUtil() {
    }

    /**
     * 支持直接运行该工具类预览 Banner。
     *
     * @param args 命令行参数（忽略）
     */
    public static void main(String[] args) {
        print(System.out);
    }

    /**
     * 获取包含 ANSI 真彩色转义序列的 Banner 文本。
     *
     * @return 泽连斯基头像文本
     */
    public static String getBanner() {
        return BANNER;
    }

    /**
     * 将 Banner 输出到指定打印流。
     *
     * @param out 输出流，例如 {@link System#out}
     */
    public static void print(PrintStream out) {
        Objects.requireNonNull(out, "out must not be null").print(BANNER);
    }

    private static String createBanner() {
        if (PIXELS.length != WIDTH * HEIGHT) {
            throw new IllegalStateException("Invalid portrait data");
        }

        StringBuilder banner = new StringBuilder(120_000);
        for (int y = 0; y < HEIGHT; y += 2) {
            banner.append("  ");
            int previousForeground = -1;
            int previousBackground = -1;

            for (int x = 0; x < WIDTH; x++) {
                int foreground = Byte.toUnsignedInt(PIXELS[y * WIDTH + x]);
                int background = Byte.toUnsignedInt(PIXELS[(y + 1) * WIDTH + x]);

                if (foreground != previousForeground) {
                    appendColor(banner, 38, PALETTE[foreground]);
                    previousForeground = foreground;
                }
                if (background != previousBackground) {
                    appendColor(banner, 48, PALETTE[background]);
                    previousBackground = background;
                }
                banner.append('\u2580');
            }
            banner.append(ANSI_RESET).append('\n');
        }
        return banner.append('\n')
                .append("                          Greater Ukraine Zelenskyy\n")
                .toString();
    }

    private static void appendColor(StringBuilder output, int colorType, int rgb) {
        output.append("\u001B[")
                .append(colorType).append(";2;")
                .append((rgb >> 16) & 0xFF).append(';')
                .append((rgb >> 8) & 0xFF).append(';')
                .append(rgb & 0xFF).append('m');
    }
